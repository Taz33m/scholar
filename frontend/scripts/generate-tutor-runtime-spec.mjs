import { createHash } from "node:crypto";
import { mkdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const frontendRoot = path.resolve(__dirname, "..");
const specDir = path.join(frontendRoot, "tutor-runtime", "spec");
const outputDir = path.join(frontendRoot, "lib", "tutor-runtime");
const outputFile = path.join(outputDir, "generated-spec.ts");

const BUNDLE_VERSION = "2026-04-14-initial";

const specFiles = [
  { key: "soul", fileName: "soul.md", exportName: "TUTOR_RUNTIME_SOUL_MARKDOWN" },
  { key: "shell", fileName: "shell.md", exportName: "TUTOR_RUNTIME_SHELL_MARKDOWN" },
  {
    key: "courseBrainSchema",
    fileName: "course_brain.schema.json",
    exportName: "TUTOR_RUNTIME_COURSE_BRAIN_SCHEMA",
    parseJson: true,
  },
  {
    key: "studentStateSchema",
    fileName: "student_state.schema.json",
    exportName: "TUTOR_RUNTIME_STUDENT_STATE_SCHEMA",
    parseJson: true,
  },
  {
    key: "promptAssembly",
    fileName: "prompt_assembly.md",
    exportName: "TUTOR_RUNTIME_PROMPT_ASSEMBLY_MARKDOWN",
  },
  {
    key: "runtimeNotes",
    fileName: "runtime_notes.md",
    exportName: "TUTOR_RUNTIME_RUNTIME_NOTES_MARKDOWN",
  },
  {
    key: "acceptanceChecklist",
    fileName: "acceptance_checklist.md",
    exportName: "TUTOR_RUNTIME_ACCEPTANCE_CHECKLIST_MARKDOWN",
  },
];

const sha256 = (value) =>
  createHash("sha256").update(value, "utf8").digest("hex");

const loadSpec = async (entry) => {
  const absolutePath = path.join(specDir, entry.fileName);
  const raw = await readFile(absolutePath, "utf8");
  const normalized = raw.replace(/\r\n/g, "\n");

  return {
    ...entry,
    absolutePath,
    raw: normalized,
    parsed: entry.parseJson ? JSON.parse(normalized) : null,
    hash: sha256(normalized),
  };
};

const main = async () => {
  const loaded = await Promise.all(specFiles.map(loadSpec));

  const bundleHash = sha256(
    loaded.map((entry) => `${entry.fileName}:${entry.hash}`).join("\n"),
  );

  const manifest = {
    bundleVersion: BUNDLE_VERSION,
    bundleHash,
    files: loaded.map((entry) => ({
      key: entry.key,
      fileName: entry.fileName,
      sha256: entry.hash,
    })),
  };

  const lines = [
    "// This file is generated by scripts/generate-tutor-runtime-spec.mjs.",
    "// Do not edit it by hand; edit tutor-runtime/spec/* and regenerate instead.",
    "",
    `export const TUTOR_RUNTIME_SPEC_MANIFEST = ${JSON.stringify(manifest, null, 2)} as const;`,
    "",
  ];

  loaded.forEach((entry) => {
    if (entry.parseJson) {
      lines.push(
        `export const ${entry.exportName} = ${JSON.stringify(entry.parsed, null, 2)} as const;`,
        "",
      );
      return;
    }

    lines.push(`export const ${entry.exportName} = ${JSON.stringify(entry.raw)};`, "");
  });

  await mkdir(outputDir, { recursive: true });
  await writeFile(outputFile, `${lines.join("\n")}\n`, "utf8");
  console.log(
    `Generated ${path.relative(frontendRoot, outputFile)} (${bundleHash.slice(0, 12)})`,
  );
};

await main();
